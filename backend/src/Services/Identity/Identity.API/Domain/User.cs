namespace Identity.Domain;

public class User
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Email { get; set; } = default!;
    public string DisplayName { get; set; } = default!;
    public string PasswordHash { get; set; } = default!;
    /// <summary>active / suspended / deleted.</summary>
    public string Status { get; set; } = "active";
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? UpdatedAt { get; set; }

    public ICollection<RefreshToken> RefreshTokens { get; set; } = new List<RefreshToken>();
}

/// <summary>
/// One row per sign-in. The token keeps the session alive; the extra columns describe
/// the device so the account owner can review the sessions and end them.
/// </summary>
public class RefreshToken
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid UserId { get; set; }
    public string TokenHash { get; set; } = default!;
    public DateTimeOffset ExpiresAt { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? RevokedAt { get; set; }
    /// <summary>opaque id generated by the browser; stable per browser profile.</summary>
    public string? DeviceId { get; set; }
    /// <summary>human label derived from the user agent, e.g. "Chrome on Windows".</summary>
    public string? DeviceLabel { get; set; }
    public string? UserAgent { get; set; }
    public string? IpAddress { get; set; }
    /// <summary>coarse location derived from the address; "Local network" for private ranges.</summary>
    public string? Location { get; set; }
    public DateTimeOffset? LastUsedAt { get; set; }
    public User? User { get; set; }
}

